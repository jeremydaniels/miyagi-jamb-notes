#!/usr/bin/env python3
"""Ask Gemini to propose the topic file list for a subject and save it to
subjects/<subject>/PLAN.md for approval.

    python tools/plan_subject.py mathematics

Reads subjects/<subject>/syllabus.md. PLAN.md is written in a fixed format that
tools/write_notes.py reads, so you can edit it by hand (rename a file, change
scope, merge or split entries) before approving it.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gemini_common as g
import syllabus_utils as su

SCHEMA = {
    "type": "OBJECT",
    "properties": {"files": {"type": "ARRAY", "items": {
        "type": "OBJECT",
        "properties": {
            "file": {"type": "STRING"},
            "section": {"type": "STRING"},
            "topic_heading": {"type": "STRING"},
            "title": {"type": "STRING"},
            "scope": {"type": "STRING"},
            "contents": {"type": "ARRAY", "items": {"type": "STRING"}},
            "objectives": {"type": "ARRAY", "items": {"type": "STRING"}},
            "split_reason": {"type": "STRING"},
            "est_words": {"type": "INTEGER"},
        },
        "required": ["file", "section", "topic_heading", "title", "scope", "contents", "objectives", "est_words"],
    }}},
    "required": ["files"],
}

PROMPT = """You are planning the file structure for detailed study notes for the JAMB UTME {title} syllabus (Nigerian secondary school students). You are given the transcribed syllabus. Propose the list of Markdown topic files.

RULES
1. One file per syllabus topic (each `###` heading under a `##` section), numbered in syllabus order. File name = <section letter><topic number>-<short-kebab-case-title>.md, for example `A1-living-organisms.md`. Section letters follow the order of the sections in the syllabus (A, B, C, ...) even when the syllabus numbers sections with Roman numerals. Use the topic number as the syllabus prints it (read "I." as 1).
2. Split a topic into parts only if the notes would otherwise exceed about {max_words} words, adding letter suffixes: `A2a-...md`, `A2b-...md`. Do not split small topics. {split_hint}
3. Keep related small topics separate (one file each); never merge two syllabus topics into one file.
4. `topic_heading` must be copied EXACTLY (character for character) from the syllabus `###` heading line, without the leading `### `. For split topics every part uses the same topic_heading.
5. `contents` and `objectives` list the item identifiers (exactly as printed, e.g. "a", "b" and "i", "ii"; for unnumbered items use "only" for the single objective or the first words of the item) that this file covers. Across all parts of a topic, every content item and every objective must appear in exactly one file, and nothing may be left out. Where the syllabus has a numbering mistake (for example a doubled marker such as "iv. iii." or "iii.sum"), use the clean label that matches the item's position in the topic (here "iii"); the transcription notes at the end of the syllabus list such mistakes.
6. `scope` is one or two plain sentences saying what the file teaches, so the writer knows where the file starts and stops. `split_reason` is only for split topics.
7. `est_words` is a realistic length of the finished notes (Biology files run 6,000 to 17,000 words; mathematics files with full worked examples run 5,000 to 10,000).
8. Existing naming examples from other subjects:
{examples}

Return JSON only.

SYLLABUS
{syllabus}
"""


def render(subject, title, files):
    out = [f"# {title} notes plan", "",
           f"Proposed topic files for `subjects/{subject}/`. Generated by `tools/plan_subject.py` from `syllabus.md`. "
           "Edit anything you like (file names, scope, which items go in which part); "
           "`tools/write_notes.py` reads this file exactly as it stands once approved.", "",
           f"**Total files: {len(files)}** · estimated words: about {sum(f['est_words'] for f in files):,}", "",
           "| # | File | Syllabus topic | Est. words |", "| --- | --- | --- | --- |"]
    for i, f in enumerate(files, 1):
        out.append(f"| {i} | `{f['file']}` | {f['topic_heading']} | {f['est_words']:,} |")
    out += ["", "## Files", ""]
    for f in files:
        out += [f"### {f['file']}", "",
                f"- Title: {f['title']}",
                f"- Section: {f['section']}",
                f"- Topic: `{f['topic_heading']}`",
                f"- Scope: {f['scope']}",
                f"- Contents: {', '.join(f['contents'])}",
                f"- Objectives: {', '.join(f['objectives'])}"]
        if f.get("split_reason"):
            out.append(f"- Split: {f['split_reason']}")
        out += [f"- Est. words: {f['est_words']}", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("subject")
    ap.add_argument("--title")
    ap.add_argument("--model", default=g.load_pricing().get("flash_model", g.default_model()),
                    help="default: the cheaper Flash model (tested OK for planning)")
    ap.add_argument("--max-words", type=int, default=10000, help="split topics longer than this (default 10000)")
    ap.add_argument("--hint", default="", help="extra guidance, e.g. which topics are big")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--out", help="write here instead of subjects/<subject>/PLAN.md (for tests)")
    a = ap.parse_args()
    sdir = g.ROOT / "subjects" / a.subject
    syl = sdir / "syllabus.md"
    out = Path(a.out) if a.out else sdir / "PLAN.md"
    if not syl.exists():
        sys.exit(f"Missing {syl}. Run transcribe_syllabus.py first.")
    if out.exists() and not a.force:
        sys.exit(f"{out} exists. Use --force to overwrite.")
    title = a.title or g.subject_title(a.subject)
    examples = []
    for other in ("biology", "use-of-english"):
        d = g.ROOT / "subjects" / other
        if d.is_dir():
            names = sorted(p.name for p in d.glob("*.md") if re.match(r"[A-Z]\d", p.name))
            examples.append(f"{other}: " + ", ".join(names[:14]))
    r = g.call_gemini([{"text": "Propose the file list now."}],
                      system=PROMPT.format(title=title, max_words=a.max_words, split_hint=a.hint,
                                           examples="\n".join(examples), syllabus=syl.read_text()),
                      model=a.model, json_schema=SCHEMA, subject=a.subject, task="plan")
    import json
    files = json.loads(r["text"])["files"]
    problems = su.check_plan(files, syl.read_text())
    warns = su.check_plan_items(files, syl.read_text())
    out.write_text(render(a.subject, title, files))
    print(f"Saved {out}: {len(files)} files. Cost ${r['cost']:.3f}")
    if problems:
        print("PLAN PROBLEMS (fix by hand or re-run):")
        for p in problems:
            print(" -", p)
    else:
        print("Plan check passed: every syllabus topic is covered and every file name and heading is valid.")
    if warns:
        print(f"{len(warns)} numbering warning(s) (syllabus numbering is irregular; review PLAN.md):")
        for w in warns[:12]:
            print(" -", w)


if __name__ == "__main__":
    main()
